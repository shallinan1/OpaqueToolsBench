#!/usr/bin/env python3
"""
Synthesize tool descriptions from multiple LLM responses.

This is Step 4 of the iterative improvement pipeline. It combines insights
from multiple LLM analyses (generated by generate_descriptions.py) into
definitive tool descriptions.

Why synthesis is needed:
- generate_descriptions.py analyzes trajectories in batches
- Different batches may reveal different patterns or contradictions
- Synthesis identifies consistent patterns vs. batch-specific noise
- Resolves conflicts by examining evidence strength

Input: llm_responses.json from generate_descriptions.py
Output: config.json with synthesized tool descriptions

The synthesis prompt asks the LLM to:
1. Identify patterns that appear across multiple responses
2. Note contradictions between responses
3. Distinguish true patterns from batch-specific noise
4. Look for emergent patterns visible only when viewing all analyses together
5. Create ONE final description per tool based on reliable patterns

Output format (in synthesis response):
    **Tool: [name]**
    Synthesis reasoning: [which patterns were consistent, how conflicts resolved]
    Final description: [definitive description for this tool]

The script parses this format and creates config.json with updated descriptions.

Example:
    python -m src.datasets.chess.synthesize_descriptions \\
        --response-dir runs/chess/.../improvements/gpt5_detailed_0.7_50000/v1 \\
        --model gpt-5 \\
        --prompt-key v1 \\
        --max-tokens 100000
"""

import os
import sys
import json
import asyncio
import argparse
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional
from datetime import datetime
from dotenv import load_dotenv

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)
load_dotenv()

from src.generation_utils.openai_parallel_generate import openai_parallel_generate, requests_url_dict, default_request_url
from src.generation_utils.rate_limits import get_rate_limit, get_token_limit
from src.generation_utils.token_tracker import aggregate_token_usage_from_responses, save_token_usage
from src.datasets.chess.prompts import CHESS_SYNTHESIS_DESCRIPTION_PROMPTS

def load_llm_responses(response_dir: Path) -> Dict:
    response_file = response_dir / "llm_responses.json"
    with open(response_file, 'r') as f:
        return json.load(f)

def extract_synthesized_descriptions(synthesis_response: str) -> Dict[str, str]:
    """Extract tool descriptions from synthesis response.

    Returns:
        Dictionary mapping tool name to description
    """
    descriptions = {}
    lines = synthesis_response.split("\n")

    current_tool = None
    in_description = False
    description_lines = []

    for line in lines:
        # Check for tool name
        if line.startswith("**Tool:"):
            # Save previous tool if exists
            if current_tool and description_lines:
                descriptions[current_tool] = " ".join(description_lines).strip()

            # Extract new tool name
            current_tool = line.replace("**Tool:", "").strip()
            current_tool = current_tool.replace("**", "").strip()
            in_description = False
            description_lines = []

        # Check for description start
        elif line.startswith("Final description:"):
            in_description = True
            # Check if description is on same line
            desc_on_line = line.replace("Final description:", "").strip()
            if desc_on_line:
                description_lines.append(desc_on_line)

        # Collect description lines
        elif in_description and line.strip() and not line.startswith("**"):
            description_lines.append(line.strip())

        # Stop collecting on next section
        elif in_description and (line.startswith("**") or line.startswith("Synthesis reasoning:")):
            in_description = False

    # Don't forget the last one
    if current_tool and description_lines:
        descriptions[current_tool] = " ".join(description_lines).strip()

    return descriptions


def load_original_config(response_dir: Path) -> Optional[Dict]:
    """Load the original config from the response directory.

    Looks for config_source in metadata from the source result directory.
    """
    # Try to get config source from generation metadata
    gen_metadata_file = response_dir / "generation_metadata.json"
    if not gen_metadata_file.exists():
        logger.warning("No generation_metadata.json found")
        return None

    with open(gen_metadata_file, 'r') as f:
        metadata = json.load(f)

    # Get the source result directory
    source_result_dir = Path(metadata.get("source_result_dir", ""))
    # Resolve to parent if a file path was saved (e.g. v0_scored.json)
    if source_result_dir.is_file():
        source_result_dir = source_result_dir.parent
    if not source_result_dir.is_dir():
        logger.warning(f"Source result directory not found: {source_result_dir}")
        return None

    # Look for metadata files in source directory to find config_source
    metadata_files = list(source_result_dir.glob("*metadata.json"))
    if not metadata_files:
        logger.warning(f"No metadata files found in {source_result_dir}")
        return None

    # Use the latest metadata file
    metadata_file = max(metadata_files, key=lambda f: f.stat().st_mtime)

    with open(metadata_file, 'r') as f:
        result_metadata = json.load(f)

    config_source = result_metadata.get("config_source")
    if not config_source:
        logger.warning("No config_source found in metadata")
        return None

    config_path = Path(config_source)
    if not config_path.exists():
        logger.warning(f"Config file not found: {config_path}")
        return None

    logger.info(f"Loading config from: {config_path}")
    with open(config_path, 'r') as f:
        return json.load(f)

def prepare_synthesis_request(
    llm_responses: Dict,
    prompt_key: str,
    model: str,
    temperature: float,
    max_tokens: int,
    reasoning_effort: str = None
) -> Dict:
    """Prepare API request for synthesis.

    Args:
        llm_responses: Dictionary containing LLM responses from generate_descriptions.py
        prompt_key: Which synthesis prompt to use
        model: Model to use for synthesis
        temperature: Temperature for generation
        max_tokens: Max tokens for generation
        reasoning_effort: Reasoning effort for reasoning models (gpt-5, o-series)
    """

    if prompt_key not in CHESS_SYNTHESIS_DESCRIPTION_PROMPTS:
        raise ValueError(f"Unknown synthesis prompt key: {prompt_key}")

    prompt_config = CHESS_SYNTHESIS_DESCRIPTION_PROMPTS[prompt_key]

    # Collect all response contents
    response_contents = []
    for idx, response in enumerate(llm_responses.get("llm_responses", []), 1):
        content = response.get("content", "")
        if content:
            response_contents.append(f"## Response {idx} (from batch {response.get('batch_idx', 0)}):\n{content}")

    if not response_contents:
        raise ValueError("No valid responses found to synthesize")

    # Build the prompt
    system_prompt = prompt_config
    user_prompt = "Here are the N LLM responses analyzing different batches of chess game trajectories:\n\n"
    user_prompt += "\n\n---\n\n".join(response_contents)
    user_prompt += "\n\n---\n\n"
    user_prompt += "Now synthesize these responses into definitive tool descriptions following the instructions above."

    # Create API request
    api_request = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ],
        "metadata": {
            "num_responses": len(response_contents),
            "synthesis": True
        }
    }

    # Handle model-specific parameters
    if model.startswith('o') or 'gpt-5' in model:
        api_request["max_completion_tokens"] = max_tokens
        if reasoning_effort is not None:
            api_request["reasoning_effort"] = reasoning_effort
    else:
        api_request["temperature"] = temperature
        api_request["max_tokens"] = max_tokens

    return api_request


def save_synthesis_results(
    response_dir: Path,
    synthesis_response: str,
    raw_response: Dict,
    model: str,
    prompt_key: str,
    temperature: float,
    max_tokens: int,
    original_config: Optional[Dict] = None,
    token_usage: Optional[Dict] = None
) -> Path:
    """Save synthesis results with hyperparameters in filename.

    Returns:
        Path to the response directory with synthesis files
    """

    # Create filename with hyperparameters
    hyper_suffix = f"{model}_{prompt_key}_{temperature}_{max_tokens}"

    # Extract synthesized descriptions
    synthesized_descriptions = extract_synthesized_descriptions(synthesis_response)
    logger.info(f"Extracted descriptions for {len(synthesized_descriptions)} tools")

    # Save synthesis metadata
    synthesis_metadata = {
        "synthesis_model": model,
        "synthesis_prompt_key": prompt_key,
        "synthesis_temperature": temperature,
        "synthesis_max_tokens": max_tokens,
        "source_response_dir": str(response_dir),
        "synthesized_timestamp": datetime.utcnow().isoformat() + "Z",
        "num_tools_synthesized": len(synthesized_descriptions)
    }

    # Save synthesis metadata with hypers in filename
    metadata_file = response_dir / f"synthesis_metadata_{hyper_suffix}.json"
    with open(metadata_file, 'w') as f:
        json.dump(synthesis_metadata, f, indent=2)

    # Save the raw synthesis response
    raw_response_file = response_dir / f"synthesis_raw_response_{hyper_suffix}.json"
    raw_response_data = {
        "metadata": synthesis_metadata,
        "raw_response": raw_response,
        "synthesis_content": synthesis_response
    }
    with open(raw_response_file, 'w') as f:
        json.dump(raw_response_data, f, indent=2)
    logger.info(f"Saved raw synthesis response: {raw_response_file}")

    # Save extracted descriptions
    descriptions_file = response_dir / f"synthesized_descriptions_{hyper_suffix}.json"
    with open(descriptions_file, 'w') as f:
        json.dump(synthesized_descriptions, f, indent=2)
    logger.info(f"Saved extracted descriptions: {descriptions_file}")

    # Create and save config with synthesized descriptions if original config available
    if original_config:
        synthesized_config = json.loads(json.dumps(original_config))  # Deep copy

        # Update descriptions in config
        updated_count = 0
        for tool in synthesized_config.get("tools", []):
            tool_name = tool.get("name", "")
            if tool_name in synthesized_descriptions:
                tool["description"] = synthesized_descriptions[tool_name]
                updated_count += 1

        # Add synthesis metadata to config
        synthesized_config["synthesis_metadata"] = synthesis_metadata

        # Save config with synthesized descriptions
        config_file = response_dir / "config.json"
        with open(config_file, 'w') as f:
            json.dump(synthesized_config, f, indent=2)

        logger.info(f"Created config with {updated_count} synthesized descriptions: {config_file}")

    # Save token usage if provided
    if token_usage:
        token_usage_path = response_dir / f"token_usage_synthesis_{hyper_suffix}.json"
        save_token_usage(token_usage, token_usage_path)

    logger.info(f"Files created with suffix: {hyper_suffix}")

    return response_dir


def main():
    """Main function for synthesizing descriptions."""

    parser = argparse.ArgumentParser(description="Synthesize tool descriptions from multiple LLM responses")
    parser.add_argument("--response-dir", type=str, required=True,
                       help="Directory containing llm_responses.json from generate_descriptions.py")
    parser.add_argument("--model", type=str, default="gpt-5",
                       help="Model to use for synthesis")
    parser.add_argument("--prompt-key", type=str, default="v1",
                       choices=list(CHESS_SYNTHESIS_DESCRIPTION_PROMPTS.keys()),
                       help="Synthesis prompt template to use")
    parser.add_argument("--temperature", type=float, default=0.3,
                       help="Temperature for synthesis (lower for more consistent synthesis)")
    parser.add_argument("--max-tokens", type=int, default=8192,
                       help="Maximum tokens for synthesis")
    parser.add_argument("--reasoning-effort", type=str, default=None,
                       choices=["minimal", "low", "medium", "high"],
                       help="Reasoning effort for reasoning models (gpt-5, o-series)")
    args = parser.parse_args()

    response_dir = Path(args.response_dir)
    if not response_dir.exists():
        logger.error(f"Response directory not found: {response_dir}")
        sys.exit(1)

    # Load LLM responses
    logger.info(f"Loading responses from {response_dir}")
    llm_responses = load_llm_responses(response_dir)

    num_responses = len(llm_responses.get("llm_responses", []))
    logger.info(f"Found {num_responses} LLM responses to synthesize")

    if num_responses == 0:
        logger.error("No responses found to synthesize")
        sys.exit(1)

    # Prepare synthesis request
    logger.info("Preparing synthesis request...")
    api_request = prepare_synthesis_request(
        llm_responses,
        args.prompt_key,
        args.model,
        args.temperature,
        args.max_tokens,
        reasoning_effort=args.reasoning_effort
    )

    # Get rate limits
    max_requests_per_minute = get_rate_limit(args.model)
    max_tokens_per_minute = get_token_limit(args.model)

    # Send request to LLM
    logger.info(f"Sending synthesis request to {args.model}...")
    responses = asyncio.run(openai_parallel_generate(
        [api_request],
        max_requests_per_minute=max_requests_per_minute,
        max_tokens_per_minute=max_tokens_per_minute,
        request_url=requests_url_dict.get(args.model, default_request_url),
    ))

    if not responses:
        logger.error("No response received from synthesis")
        sys.exit(1)

    # Extract synthesis response
    response_data = responses[0]
    raw_response = response_data[1]
    synthesis_response = raw_response["choices"][0]["message"]["content"]

    # Track token usage
    token_usage = aggregate_token_usage_from_responses(responses, model=args.model)
    logger.info(f"Synthesis token usage: {token_usage['total_tokens']:,} tokens")

    # Load original config if available
    original_config = load_original_config(response_dir)
    if original_config:
        logger.info("Loaded original config for creating synthesized config")
    else:
        logger.info("No original config found - will save descriptions only")

    # Save results
    save_synthesis_results(
        response_dir,
        synthesis_response,
        raw_response,
        args.model,
        args.prompt_key,
        args.temperature,
        args.max_tokens,
        original_config,
        token_usage
    )

    logger.info("\nSynthesis complete!")
    logger.info("\nSynthesized descriptions:")
    logger.info("-" * 60)
    print(synthesis_response)


if __name__ == "__main__":
    main()